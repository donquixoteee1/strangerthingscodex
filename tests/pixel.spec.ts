import {test,expect} from '@playwright/test';
test('crisp pixels and ASCII density preserve input and independent settings',async({page})=>{
 await page.goto('/');
 const art=page.locator('.alphabet-art.pixel-art');
 await expect.poll(()=>art.evaluate((n:HTMLImageElement)=>n.naturalWidth)).toBeGreaterThan(0);
 await expect(page.getByRole('button',{name:'Compare',exact:true})).toHaveCount(0);
 await expect(page.getByText('Stranger Codex',{exact:true})).toHaveCount(0);
 const fine=await art.evaluate((n:HTMLImageElement)=>n.naturalWidth);
 await page.locator('#message').fill('HELLO');
 await page.locator('#pixel-size').fill('8');
 await expect(page.locator('#pixel-value')).toHaveText('8 px');
 await expect.poll(()=>art.evaluate((n:HTMLImageElement)=>n.naturalWidth)).toBeLessThan(fine);
 // Every output sample is fully opaque or transparent, with no blended edge alpha.
 expect(await art.evaluate((n:HTMLImageElement)=>{const c=document.createElement('canvas');c.width=n.naturalWidth;c.height=n.naturalHeight;const ctx=c.getContext('2d')!;ctx.drawImage(n,0,0);return [...ctx.getImageData(0,0,c.width,c.height).data].every((v,i)=>i%4!==3||v===0||v===255);})).toBe(true);
 await page.locator('#pixel-size').fill('4');
 await page.screenshot({path:'artifacts/preview-pixel.png'});
 await page.getByRole('button',{name:'ASCII',exact:true}).click();
 await expect(page.getByLabel('Size')).toBeEnabled();
 const animated=await art.getAttribute('src');
 await expect.poll(()=>art.getAttribute('src'),{timeout:7000}).not.toBe(animated);
 await page.locator('#motion').uncheck();
 await page.locator('#pixel-size').fill('2');
 const sparse=decodeURIComponent((await art.getAttribute('src'))!);
 await page.locator('#pixel-size').fill('9');
 const dense=decodeURIComponent((await art.getAttribute('src'))!);
 expect(dense.length).toBeGreaterThan(sparse.length);
 await expect(page.locator('#pixel-value')).toHaveText('9/10');
 await expect(page.locator('#message')).toHaveValue('HELLO');
 await page.locator('#pixel-size').fill('7');
 await page.screenshot({path:'artifacts/preview-ascii-density.png'});
 await page.getByRole('button',{name:'Pixel',exact:true}).click();
 await expect(page.locator('#pixel-size')).toHaveValue('4');
 await page.getByRole('button',{name:'ASCII',exact:true}).click();
 await expect(page.locator('#pixel-size')).toHaveValue('7');
 await page.locator('#skin').uncheck();await page.locator('#skin').check();
 await expect(page.locator('.alphabet-art.pixel-art')).toHaveCount(1);
 await expect(page.locator('#message')).toHaveValue('HELLO');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
 await page.screenshot({path:'artifacts/preview-pixel-mobile.png'});
});
